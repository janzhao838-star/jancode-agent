def builtin_agents() -> list[dict]:
    installed = {a.name for a in list_agents()}
    out = []
    for item in BUILTIN_AGENTS:
        row = dict(item)
        row["installed"] = row["name"] in installed
        out.append(row)
    return out


def install_builtin_agent(name: str) -> bool:
    for item in BUILTIN_AGENTS:
        if item["name"] == name:
            upsert_agent(name, item["prompt"], "", [])
            return True
    return False


